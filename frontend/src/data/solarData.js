// Calculate subsidy based on system capacity kW and state
export function calculateSubsidy(capacityKw, stateId = "MH") {
  const state = statesData.find(s => s.id === stateId) || statesData[0];
  const kw = Number(capacityKw) || 1;

  // PM Surya Ghar national formula:
  // 1 kW: ₹30,000
  // 2 kW: ₹60,000
  // 3 kW or more: ₹78,000 max central subsidy
  let centralSubsidy = 0;
  if (kw <= 1) {
    centralSubsidy = 30000;
  } else if (kw === 2) {
    centralSubsidy = 60000;
  } else {
    centralSubsidy = 78000;
  }

  const stateSubsidy = state.stateSubsidyBonus || 0;
  const totalSubsidy = centralSubsidy + stateSubsidy;
  
  // Total approximate system cost without subsidy
  const ratePerKw = state.solarRatePerKw || 65000;
  const totalSystemCost = kw * ratePerKw;
  const estimatedCostAfterSubsidy = Math.max(totalSystemCost - totalSubsidy, 15000);

  return {
    centralSubsidy,
    stateSubsidy,
    totalSubsidy,
    totalSystemCost,
    estimatedCostAfterSubsidy
  };
}
